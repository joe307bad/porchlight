// Writes Runtime/Shared/Life/PersonNames.cs: the first and last names the
// townsfolk are given, taken from faker-js's English locale (@faker-js/faker,
// MIT: https://github.com/faker-js/faker). Only the lists come over, as data;
// which name each person gets is PersonNames.Of's, seeded by their town and who
// they are, so every game, the server and Manage give them the same one.
//
//   cd unity/Tools~/names && npm install && npm run generate

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { faker } from '@faker-js/faker/locale/en';

const person = faker.rawDefinitions.person;
const first = [...new Set(person.first_name.generic)];
const last = [...new Set(person.last_name.generic)];
const list = (xs) => xs.map((s) => JSON.stringify(s)).reduce((lines, s) => {
  const l = lines[lines.length - 1];
  if (l.length + s.length + 2 > 116) lines.push(s + ',');
  else lines[lines.length - 1] = `${l}${l ? ' ' : ''}${s},`;
  return lines;
}, ['']).map((l) => `            ${l}`).join('\n');

const out = `// Generated by unity/Tools~/names/generate.mjs from faker-js's English name
// lists (@faker-js/faker 9.9.0, MIT, https://github.com/faker-js/faker). Don't
// edit by hand: change the generator and run it again.

namespace Porchlight.Life
{
    public static partial class PersonNames
    {
        static readonly string[] FIRST =
        {
${list(first)}
        };

        static readonly string[] LAST =
        {
${list(last)}
        };
    }
}
`;
const to = fileURLToPath(new URL('../../Assets/Porchlight/Runtime/Shared/Life/PersonNames.Lists.cs', import.meta.url));
writeFileSync(to, out);
console.log(`${first.length} first names, ${last.length} last names -> ${to}`);
